"""Error analysis on real predictions -> docs/ERROR_ANALYSIS.md.

Profanity in quoted examples is masked (first letter + asterisks) so the repo stays readable;
the labels and predictions are unchanged.
"""

from __future__ import annotations

import json
import re

import pandas as pd

from hybridmod.config import load_config
from hybridmod.data import llm_sample, load_split
from hybridmod.rules import RuleEngine, normalise_token

MASK_MIN_LEN = 3


def masker(cfg):
    eng = RuleEngine.from_file(cfg.rules, cfg.path(cfg.rules.lexicon_path))

    def mask(text: str, limit: int = 220) -> str:
        text = re.sub(r"\s+", " ", text).strip()
        if len(text) > limit:
            text = text[:limit].rsplit(" ", 1)[0] + " ..."

        def repl(m):
            w = m.group(0)
            t = normalise_token(w)
            if len(t) >= MASK_MIN_LEN and eng.lexicon_hits(w):
                return w[0] + "*" * (len(w) - 1)
            return w

        return re.sub(r"[A-Za-z0-9@$!*]+", repl, text).replace("|", "/")

    return mask


def table(rows, cols) -> list[str]:
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    return out


def main() -> None:
    cfg = load_config()
    mask = masker(cfg)
    s = pd.read_csv(cfg.path("results/predictions_sample.csv"))
    st = llm_sample(len(s)).set_index("uid")
    s["text"] = [mask(st.loc[u, "comment_text"]) for u in s.uid]
    s["p_ml"] = s.p_ml.round(3)
    lines = ["# Error analysis (real predictions, generated by scripts/error_analysis.py)", "",
             "Labels are Civil Comments crowd labels (toxic if >= 50% of raters said so). "
             "Profanity in examples is masked.", ""]

    def section(title, df, cols, n=8):
        lines.extend([f"## {title} ({len(df)} on the sample)", ""])
        if len(df):
            lines.extend(table(df.head(n).to_dict("records"), cols))
        lines.append("")

    cols = ["uid", "toxicity", "p_ml", "llm_category", "text"]
    section("ML false positives the LLM corrected (hybrid band)",
            s[(s.ml_flag == 1) & (s.toxicity == 0) & (s.hybrid_flag == 0) & (s.hybrid_stage == "llm")],
            cols)
    section("ML false negatives the LLM caught (hybrid band)",
            s[(s.ml_flag == 0) & (s.toxicity == 1) & (s.hybrid_flag == 1) & (s.hybrid_stage == "llm")],
            cols)
    section("Hybrid false positives that mention an identity group",
            s[(s.hybrid_flag == 1) & (s.toxicity == 0) & (s.identity_any == 1)], cols)
    section("LLM false positives (LLM says violating, raters said not toxic)",
            s[(s.llm_flag == 1) & (s.toxicity == 0)], cols)
    section("LLM false negatives (raters said toxic, LLM allowed)",
            s[(s.llm_flag == 0) & (s.toxicity == 1)], cols)

    # LLM category vs label on the sample
    ct = pd.crosstab(s.llm_category, s.toxicity).rename(columns={0: "label 0", 1: "label 1"})
    lines += ["## LLM category vs crowd label (sample)", "",
              *table([{"category": k, **v} for k, v in ct.to_dict("index").items()],
                     ["category", "label 0", "label 1"]), ""]

    pt = cfg.path("results/predictions_test.csv")
    if pt.exists():
        t = pd.read_csv(pt)
        test = load_split("test").set_index("uid")
        rb = t[t.rule == "lexicon"]
        lines += ["## Stage-1 lexicon blocks on the full test split", "",
                  f"{len(rb)} comments blocked by the hashed lexicon; {int(rb.toxicity.sum())} of "
                  f"them are labelled toxic (precision {rb.toxicity.mean():.3f}). "
                  "Non-toxic examples:", ""]
        ex = rb[rb.toxicity == 0].head(5)
        lines += table([{"uid": u, "text": mask(test.loc[u, "comment_text"])} for u in ex.uid],
                       ["uid", "text"])
        lines.append("")
    out = cfg.path("docs/ERROR_ANALYSIS.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(json.dumps({"written": str(out), "lines": len(lines)}))


if __name__ == "__main__":
    main()
